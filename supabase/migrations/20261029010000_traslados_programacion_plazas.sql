-- SIGO: traslados programados de agentes y controladores.
-- Aplicar en SIGO-TEST antes de desplegar el backend (ddl-auto=validate).
create extension if not exists btree_gist;
create table if not exists public.traslados_programados_plaza (
    id bigint generated by default as identity primary key,
    trabajador_id bigint not null references public.trabajadores(id),
    plaza_origen_id bigint not null references public.plazas(id),
    plaza_destino_id bigint not null references public.plazas(id),
    fecha_inicio date not null,
    fecha_fin date,
    estado varchar(16) not null default 'PROGRAMADO',
    creado_por bigint not null references public.trabajadores(id),
    created_at timestamptz not null default now(),
    constraint ck_traslado_plaza_distinta check (plaza_origen_id <> plaza_destino_id),
    constraint ck_traslado_fechas check (fecha_fin is null or fecha_fin >= fecha_inicio),
    constraint ck_traslado_estado check (estado in ('PROGRAMADO','CANCELADO'))
);
-- Proteccion en PostgreSQL contra traslados simultaneos del mismo trabajador.
do $$
begin
  if not exists (select 1 from pg_constraint where conname='ex_traslado_trabajador_periodo') then
    alter table public.traslados_programados_plaza
      add constraint ex_traslado_trabajador_periodo
      exclude using gist (
        trabajador_id with =,
        daterange(fecha_inicio, coalesce(fecha_fin, 'infinity'::date), '[]') with &&
      ) where (estado='PROGRAMADO');
  end if;
end $$;
create index if not exists idx_traslados_plaza_origen_fecha
    on public.traslados_programados_plaza(plaza_origen_id, fecha_inicio);
create index if not exists idx_traslados_plaza_destino_fecha
    on public.traslados_programados_plaza(plaza_destino_id, fecha_inicio);
revoke all on public.traslados_programados_plaza from anon, authenticated;
