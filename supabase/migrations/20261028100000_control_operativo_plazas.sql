-- SIGO | Control operativo de plazas (TRAZA integrado sin modificar incidencias)
create table if not exists public.control_operativo_reportes (
  id bigint generated by default as identity primary key,
  plaza_id bigint not null references public.plazas(id),
  turno_id bigint not null references public.turnos(id),
  via_id bigint references public.vias(id),
  registrado_por_id bigint not null references public.trabajadores(id),
  tipo varchar(12) not null check (tipo in ('REPORTE','MEDICION')),
  fecha date not null,
  hora time without time zone not null,
  situacion varchar(60) not null default '',
  ingreso varchar(60) not null default '',
  incidente varchar(120) not null default '',
  cola_metros integer check (cola_metros between 0 and 50000),
  descripcion text not null default '',
  estado varchar(20) not null default 'REGISTRADO'
    check (estado in ('REGISTRADO','EN_OBSERVACION','ATENDIDO')),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint co_medicion_cola check (tipo <> 'MEDICION' or cola_metros is not null)
);
create index if not exists idx_co_reportes_plaza_fecha
  on public.control_operativo_reportes (plaza_id,fecha desc,hora desc);
create index if not exists idx_co_reportes_fecha
  on public.control_operativo_reportes (fecha desc, tipo);
create table if not exists public.control_operativo_evidencias (
  id bigint generated by default as identity primary key,
  reporte_id bigint not null references public.control_operativo_reportes(id) on delete cascade,
  categoria varchar(20) not null check (categoria in ('PLAZA','INGRESO','INCIDENTE','COLA')),
  url_archivo text not null,
  public_id text,
  creado_en timestamptz not null default now()
);
create index if not exists idx_co_evidencias_reporte
  on public.control_operativo_evidencias (reporte_id);
-- SIGO accede mediante backend con credenciales de base de datos; bloquear Data API directa.
alter table public.control_operativo_reportes enable row level security;
alter table public.control_operativo_evidencias enable row level security;
revoke all on public.control_operativo_reportes from anon, authenticated;
revoke all on public.control_operativo_evidencias from anon, authenticated;
revoke all on sequence public.control_operativo_reportes_id_seq from anon, authenticated;
revoke all on sequence public.control_operativo_evidencias_id_seq from anon, authenticated;
comment on table public.control_operativo_reportes is 'Reportes y mediciones operativas integradas desde TRAZA; independientes de las incidencias existentes en SIGO.';
comment on table public.control_operativo_evidencias is 'Evidencias Cloudinary del control operativo, gestionadas exclusivamente mediante la API SIGO.';
