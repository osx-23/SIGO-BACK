-- Fuente de datos: requerimiento y stock reportado de septiembre de 2026.
-- Los blancos se guardan como NULL. La solicitud no es consumo medido.
-- La carga histórica real se realiza por separado con el archivo SQL de importación.
CREATE TABLE IF NOT EXISTS public.inventario_referencia_mensual (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo DATE NOT NULL CHECK (EXTRACT(DAY FROM periodo)=1),
  plaza_id BIGINT NOT NULL REFERENCES public.plazas(id),
  producto_id BIGINT NOT NULL REFERENCES public.inventario_producto(id),
  codigo_producto VARCHAR(60) NOT NULL,
  cantidad_solicitada NUMERIC(12,2),
  consumo_reportado NUMERIC(12,2),
  stock_reportado NUMERIC(12,2),
  fila_excel INTEGER NOT NULL,
  archivo_origen TEXT NOT NULL,
  importado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT inventario_ref_mes_plaza_codigo UNIQUE(periodo,plaza_id,codigo_producto),
  CONSTRAINT inventario_ref_algun_dato CHECK
    (cantidad_solicitada IS NOT NULL OR consumo_reportado IS NOT NULL OR stock_reportado IS NOT NULL),
  CONSTRAINT inventario_ref_positivos CHECK
    ((cantidad_solicitada IS NULL OR cantidad_solicitada>=0) AND
     (consumo_reportado IS NULL OR consumo_reportado>=0) AND
     (stock_reportado IS NULL OR stock_reportado>=0))
);
CREATE INDEX IF NOT EXISTS idx_inventario_ref_producto_plaza_periodo
 ON public.inventario_referencia_mensual(producto_id,plaza_id,periodo DESC);
ALTER TABLE public.inventario_referencia_mensual ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.inventario_referencia_mensual FROM anon,authenticated;

-- Último conteo finalizado tiene prioridad cuando es posterior al mes de referencia.
-- En ausencia de conteo posterior, stock reportado en septiembre es el saldo de referencia.
-- Se suman entregas realizadas a partir del mes siguiente al corte de referencia.
-- Un stock sin registro permanece en 0 técnico, pero origen_stock='SIN_REGISTRO'.
CREATE OR REPLACE VIEW public.v_inventario_stock_actual AS
WITH ultimo_conteo AS (
 SELECT DISTINCT ON (i.plaza_id,d.producto_id)
  i.plaza_id,d.producto_id,i.id AS inventario_id,
  i.fecha_finalizacion,d.cantidad_encontrada
 FROM public.inventario_conteo i
 JOIN public.inventario_conteo_detalle d ON d.inventario_id=i.id
 WHERE i.estado::text='FINALIZADO'
 ORDER BY i.plaza_id,d.producto_id,i.fecha_finalizacion DESC,i.id DESC
), ultima_referencia AS (
 SELECT DISTINCT ON (r.plaza_id,r.producto_id)
  r.plaza_id,r.producto_id,r.periodo,r.stock_reportado
 FROM public.inventario_referencia_mensual r
 WHERE r.stock_reportado IS NOT NULL
 ORDER BY r.plaza_id,r.producto_id,r.periodo DESC,r.id DESC
), base AS (
 SELECT pp.plaza_id,pp.producto_id,pl.codigo AS plaza,
    p.nombre::varchar(200) AS producto,p.unidad_medida::varchar(80) AS unidad_medida,
    (uc.fecha_finalizacion IS NOT NULL AND
      (ref.periodo IS NULL OR uc.fecha_finalizacion >=
         (ref.periodo + INTERVAL '1 month')::timestamptz)) AS usa_conteo,
    uc.inventario_id,uc.fecha_finalizacion,uc.cantidad_encontrada,
    ref.stock_reportado,ref.periodo AS periodo_referencia
 FROM public.inventario_producto_plaza pp
 JOIN public.inventario_producto p ON p.id=pp.producto_id
 JOIN public.plazas pl ON pl.id=pp.plaza_id
 LEFT JOIN ultimo_conteo uc ON uc.plaza_id=pp.plaza_id AND uc.producto_id=pp.producto_id
 LEFT JOIN ultima_referencia ref ON ref.plaza_id=pp.plaza_id AND ref.producto_id=pp.producto_id
), puntos AS (
 SELECT b.*,
 CASE WHEN b.usa_conteo THEN b.fecha_finalizacion
      WHEN b.periodo_referencia IS NOT NULL
      THEN (b.periodo_referencia + INTERVAL '1 month')::timestamptz
      ELSE NULL END AS corte,
 CASE WHEN b.usa_conteo THEN b.cantidad_encontrada
      ELSE b.stock_reportado END AS cantidad_base
 FROM base b
)
SELECT x.plaza_id,x.plaza,x.producto_id,x.producto,x.unidad_medida,
       (COALESCE(x.cantidad_base,0)+COALESCE(e.cantidad,0))::numeric(12,2) AS cantidad_actual,
       (CASE WHEN x.usa_conteo THEN x.inventario_id ELSE 0 END)::bigint AS inventario_id,
       (CASE WHEN x.usa_conteo THEN GREATEST(x.fecha_finalizacion,e.ultima_fecha)
             ELSE e.ultima_fecha END)::timestamptz AS actualizado_en,
       (CASE WHEN x.usa_conteo THEN 'CONTEO'
             WHEN x.stock_reportado IS NOT NULL THEN 'EXCEL_SEPTIEMBRE'
             WHEN e.cantidad IS NOT NULL THEN 'RECEPCION'
             ELSE 'SIN_REGISTRO' END)::text AS origen_stock,
       (CASE WHEN x.usa_conteo THEN NULL ELSE x.periodo_referencia END)::date AS periodo_referencia
FROM puntos x
LEFT JOIN LATERAL (
 SELECT SUM(rd.cantidad) AS cantidad,MAX(r.creado_en) AS ultima_fecha
 FROM public.inventario_pedido_recepcion_detalle rd
 JOIN public.inventario_pedido_recepcion r ON r.id=rd.recepcion_id
 JOIN public.inventario_pedido ped ON ped.id=r.pedido_id
 WHERE ped.plaza_id=x.plaza_id AND rd.producto_id=x.producto_id
 AND (x.corte IS NULL OR r.creado_en>x.corte)
) e ON TRUE;
ALTER VIEW public.v_inventario_stock_actual SET (security_invoker=true);
REVOKE ALL ON public.v_inventario_stock_actual FROM anon,authenticated;
