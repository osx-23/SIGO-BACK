-- SIGO: traslados trazables entre plazas.
-- Se resta al despachar y se suma al confirmar la recepción.
CREATE TABLE IF NOT EXISTS public.inventario_traslado (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origen_plaza_id BIGINT NOT NULL REFERENCES public.plazas(id),
  destino_plaza_id BIGINT NOT NULL REFERENCES public.plazas(id),
  producto_id BIGINT NOT NULL REFERENCES public.inventario_producto(id),
  cantidad NUMERIC(14,2) NOT NULL CHECK (cantidad > 0),
  estado VARCHAR(20) NOT NULL DEFAULT 'EN_TRANSITO' CHECK (estado IN ('EN_TRANSITO','RECIBIDO')),
  observacion TEXT,
  enviado_por BIGINT NOT NULL REFERENCES public.trabajadores(id),
  enviado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  recibido_por BIGINT REFERENCES public.trabajadores(id),
  recibido_en TIMESTAMPTZ,
  CONSTRAINT inventario_traslado_plazas_distintas CHECK (origen_plaza_id <> destino_plaza_id),
  CONSTRAINT inventario_traslado_recepcion_consistente CHECK (
    (estado='EN_TRANSITO' AND recibido_por IS NULL AND recibido_en IS NULL)
    OR (estado='RECIBIDO' AND recibido_por IS NOT NULL AND recibido_en IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS idx_inventario_traslado_origen ON public.inventario_traslado(origen_plaza_id,producto_id,enviado_en);
CREATE INDEX IF NOT EXISTS idx_inventario_traslado_destino ON public.inventario_traslado(destino_plaza_id,producto_id,estado,recibido_en);
ALTER TABLE public.inventario_traslado ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.inventario_traslado FROM anon, authenticated;

-- El último conteo válido prevalece sobre movimientos anteriores;
-- el saldo histórico de septiembre solo sirve de base referencial.
CREATE OR REPLACE VIEW public.v_inventario_stock_actual AS
WITH ultimo_conteo AS (
 SELECT DISTINCT ON (i.plaza_id,d.producto_id)
  i.plaza_id,d.producto_id,i.id inventario_id,
  i.fecha_finalizacion,d.cantidad_encontrada
 FROM public.inventario_conteo i
 JOIN public.inventario_conteo_detalle d ON d.inventario_id=i.id
 WHERE i.estado::text='FINALIZADO'
 ORDER BY i.plaza_id,d.producto_id,i.fecha_finalizacion DESC,i.id DESC
), ultima_referencia AS (
 SELECT DISTINCT ON (r.plaza_id,r.producto_id)
  r.plaza_id,r.producto_id,r.periodo,r.stock_reportado
 FROM public.inventario_referencia_mensual r
 WHERE r.stock_reportado IS NOT NULL
 ORDER BY r.plaza_id,r.producto_id,r.periodo DESC,r.id DESC
), base AS (
 SELECT pp.plaza_id,pp.producto_id,pl.codigo plaza,
   p.nombre::varchar(200) producto,p.unidad_medida::varchar(80) unidad_medida,
   (uc.fecha_finalizacion IS NOT NULL AND
    (ref.periodo IS NULL OR uc.fecha_finalizacion >=
     (ref.periodo+INTERVAL '1 month')::timestamptz)) usa_conteo,
   uc.inventario_id,uc.fecha_finalizacion,uc.cantidad_encontrada,
   ref.stock_reportado,ref.periodo periodo_referencia
 FROM public.inventario_producto_plaza pp
 JOIN public.inventario_producto p ON p.id=pp.producto_id
 JOIN public.plazas pl ON pl.id=pp.plaza_id
 LEFT JOIN ultimo_conteo uc ON uc.plaza_id=pp.plaza_id AND uc.producto_id=pp.producto_id
 LEFT JOIN ultima_referencia ref ON ref.plaza_id=pp.plaza_id AND ref.producto_id=pp.producto_id
), puntos AS (
 SELECT b.*,
   CASE WHEN b.usa_conteo THEN b.fecha_finalizacion
        WHEN b.periodo_referencia IS NOT NULL
        THEN (b.periodo_referencia+INTERVAL '1 month')::timestamptz
        ELSE NULL END corte,
   CASE WHEN b.usa_conteo THEN b.cantidad_encontrada ELSE b.stock_reportado END cantidad_base
 FROM base b
)
SELECT x.plaza_id,x.plaza,x.producto_id,x.producto,x.unidad_medida,
  (COALESCE(x.cantidad_base,0)+COALESCE(e.cantidad,0)
   +COALESCE(t.entradas,0)-COALESCE(t.salidas,0))::numeric(12,2) cantidad_actual,
  (CASE WHEN x.usa_conteo THEN x.inventario_id ELSE 0 END)::bigint inventario_id,
  (CASE WHEN x.usa_conteo THEN GREATEST(x.fecha_finalizacion,e.ultima_fecha,t.ultima_fecha)
        ELSE GREATEST(e.ultima_fecha,t.ultima_fecha) END)::timestamptz actualizado_en,
  (CASE WHEN x.usa_conteo THEN 'CONTEO'
        WHEN x.stock_reportado IS NOT NULL THEN 'EXCEL_SEPTIEMBRE'
        WHEN e.cantidad IS NOT NULL THEN 'RECEPCION'
        WHEN t.entradas IS NOT NULL THEN 'TRASLADO'
        ELSE 'SIN_REGISTRO' END)::text origen_stock,
  (CASE WHEN x.usa_conteo THEN NULL ELSE x.periodo_referencia END)::date periodo_referencia
FROM puntos x
LEFT JOIN LATERAL (
 SELECT SUM(rd.cantidad) cantidad,MAX(r.creado_en) ultima_fecha
 FROM public.inventario_pedido_recepcion_detalle rd
 JOIN public.inventario_pedido_recepcion r ON r.id=rd.recepcion_id
 JOIN public.inventario_pedido ped ON ped.id=r.pedido_id
 WHERE ped.plaza_id=x.plaza_id AND rd.producto_id=x.producto_id
   AND (x.corte IS NULL OR r.creado_en>x.corte)
) e ON TRUE
LEFT JOIN LATERAL (
 SELECT SUM(z.entradas) entradas,SUM(z.salidas) salidas,MAX(z.fecha) ultima_fecha
 FROM (
   SELECT tr.cantidad entradas,0::numeric salidas,tr.recibido_en fecha
   FROM public.inventario_traslado tr
   WHERE tr.destino_plaza_id=x.plaza_id AND tr.producto_id=x.producto_id
     AND tr.estado='RECIBIDO'
     AND (x.corte IS NULL OR tr.recibido_en>x.corte)
   UNION ALL
   SELECT 0::numeric entradas,tr.cantidad salidas,tr.enviado_en fecha
   FROM public.inventario_traslado tr
   WHERE tr.origen_plaza_id=x.plaza_id AND tr.producto_id=x.producto_id
     AND (x.corte IS NULL OR tr.enviado_en>x.corte)
 ) z
) t ON TRUE;

-- El traslado NO es consumo: se neutraliza en el cálculo entre conteos.
CREATE OR REPLACE VIEW public.v_inventario_consumo_mensual AS
WITH lecturas AS (
 SELECT i.plaza_id,d.producto_id,i.fecha_finalizacion fecha,
 d.cantidad_encontrada actual,
 LAG(i.fecha_finalizacion) OVER w anterior_fecha,
 LAG(d.cantidad_encontrada) OVER w anterior
 FROM public.inventario_conteo i
 JOIN public.inventario_conteo_detalle d ON d.inventario_id=i.id
 WHERE i.estado::text='FINALIZADO'
 WINDOW w AS (PARTITION BY i.plaza_id,d.producto_id ORDER BY i.fecha_finalizacion,i.id)
), consumos AS (
 SELECT l.plaza_id,l.producto_id,DATE_TRUNC('month',l.fecha)::date periodo,
 GREATEST(0,l.anterior+
 COALESCE((SELECT SUM(rd.cantidad)
   FROM public.inventario_pedido_recepcion_detalle rd
   JOIN public.inventario_pedido_recepcion r ON r.id=rd.recepcion_id
   JOIN public.inventario_pedido p ON p.id=r.pedido_id
   WHERE p.plaza_id=l.plaza_id AND rd.producto_id=l.producto_id
    AND r.creado_en>l.anterior_fecha AND r.creado_en<=l.fecha),0)
 +COALESCE((SELECT SUM(tr.cantidad) FROM public.inventario_traslado tr
   WHERE tr.destino_plaza_id=l.plaza_id AND tr.producto_id=l.producto_id
     AND tr.estado='RECIBIDO' AND tr.recibido_en>l.anterior_fecha AND tr.recibido_en<=l.fecha),0)
 -COALESCE((SELECT SUM(tr.cantidad) FROM public.inventario_traslado tr
   WHERE tr.origen_plaza_id=l.plaza_id AND tr.producto_id=l.producto_id
     AND tr.enviado_en>l.anterior_fecha AND tr.enviado_en<=l.fecha),0)
 -l.actual) consumo
 FROM lecturas l WHERE l.anterior_fecha IS NOT NULL
)
SELECT plaza_id,producto_id,periodo,SUM(consumo)::numeric(14,2) consumo
FROM consumos GROUP BY plaza_id,producto_id,periodo;

ALTER VIEW public.v_inventario_stock_actual SET (security_invoker=true);
ALTER VIEW public.v_inventario_consumo_mensual SET (security_invoker=true);
REVOKE ALL ON public.v_inventario_stock_actual,public.v_inventario_consumo_mensual FROM anon,authenticated;
