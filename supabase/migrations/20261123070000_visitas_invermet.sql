-- Visitas de fiscalización INVERMET, independientes de las incidencias operativas.
create table if not exists public.visitas_invermet (
  id bigint generated by default as identity primary key,
  plaza_id bigint not null references public.plazas(id),
  registrado_por_id bigint not null references public.trabajadores(id),
  fecha date not null,
  hora_inicio time without time zone not null,
  hora_final time without time zone not null,
  controlador varchar(150) not null,
  supervisor varchar(150) not null,
  casetas_en_plaza integer not null check (casetas_en_plaza between 0 and 200),
  casetas_abiertas integer not null check (casetas_abiertas between 0 and casetas_en_plaza),
  dato_visita_1 varchar(300) not null default '',
  dato_visita_2 varchar(300) not null default '',
  observaciones text not null default '',
  creado_en timestamptz not null default now()
);
create index if not exists idx_visitas_invermet_fecha_plaza
  on public.visitas_invermet (fecha desc, plaza_id);

create table if not exists public.visita_invermet_preguntas (
  id bigint generated by default as identity primary key,
  visita_id bigint not null references public.visitas_invermet(id) on delete cascade,
  numero integer not null check (numero between 1 and 5),
  pregunta varchar(300) not null,
  quien_respondio varchar(150) not null default '',
  respuesta varchar(1000) not null default '',
  unique (visita_id, numero)
);
create table if not exists public.visita_invermet_fotos (
  id bigint generated by default as identity primary key,
  visita_id bigint not null references public.visitas_invermet(id) on delete cascade,
  url_archivo varchar(1000) not null,
  public_id varchar(500) not null,
  creado_en timestamptz not null default now()
);
create index if not exists idx_visita_invermet_fotos_visita
  on public.visita_invermet_fotos (visita_id);
-- El acceso a las visitas y fotos se realiza únicamente por el backend autenticado.
alter table public.visitas_invermet enable row level security;
alter table public.visita_invermet_preguntas enable row level security;
alter table public.visita_invermet_fotos enable row level security;
revoke all on public.visitas_invermet, public.visita_invermet_preguntas, public.visita_invermet_fotos from anon, authenticated;
revoke all on sequence public.visitas_invermet_id_seq, public.visita_invermet_preguntas_id_seq, public.visita_invermet_fotos_id_seq from anon, authenticated;
comment on table public.visitas_invermet is 'Actas de visita de fiscalización de INVERMET a plazas de SIGO.';
