-- SIGO: pedidos mensuales, recepciones parciales y stock trazable.
-- Ejecutar tras desplegar la API compatible. No modifica conteos históricos.
CREATE TABLE IF NOT EXISTS public.inventario_pedido (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plaza_id BIGINT NOT NULL REFERENCES public.plazas(id),
  periodo DATE NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'BORRADOR'
    CHECK (estado IN ('BORRADOR','PENDIENTE','APROBADO','ENVIADO','PARCIAL','COMPLETADO','CERRADO_FALTANTES','RECHAZADO')),
  observacion TEXT,
  creado_por BIGINT NOT NULL REFERENCES public.trabajadores(id),
  aprobado_por BIGINT REFERENCES public.trabajadores(id),
  aprobado_en TIMESTAMPTZ,
  enviado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT inventario_pedido_periodo_mes CHECK (EXTRACT(DAY FROM periodo) = 1),
  CONSTRAINT inventario_pedido_plaza_periodo UNIQUE (plaza_id, periodo)
);

CREATE TABLE IF NOT EXISTS public.inventario_pedido_detalle (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES public.inventario_pedido(id) ON DELETE CASCADE,
  producto_id BIGINT NOT NULL REFERENCES public.inventario_producto(id),
  cantidad_solicitada NUMERIC(14,2) NOT NULL CHECK (cantidad_solicitada >= 0),
  cantidad_sugerida NUMERIC(14,2) CHECK (cantidad_sugerida >= 0),
  promedio_mensual NUMERIC(14,2) CHECK (promedio_mensual >= 0),
  stock_referencia NUMERIC(14,2) CHECK (stock_referencia >= 0),
  CONSTRAINT inventario_pedido_detalle_unico UNIQUE (pedido_id, producto_id)
);

CREATE TABLE IF NOT EXISTS public.inventario_pedido_recepcion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES public.inventario_pedido(id),
  clave_idempotencia UUID NOT NULL,
  recibido_por BIGINT NOT NULL REFERENCES public.trabajadores(id),
  observacion TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT inventario_recepcion_clave_unica UNIQUE (pedido_id, clave_idempotencia)
);

CREATE TABLE IF NOT EXISTS public.inventario_pedido_recepcion_detalle (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recepcion_id BIGINT NOT NULL REFERENCES public.inventario_pedido_recepcion(id) ON DELETE RESTRICT,
  producto_id BIGINT NOT NULL REFERENCES public.inventario_producto(id),
  cantidad NUMERIC(14,2) NOT NULL CHECK (cantidad > 0),
  CONSTRAINT inventario_recepcion_producto_unico UNIQUE (recepcion_id, producto_id)
);

CREATE INDEX IF NOT EXISTS idx_inventario_pedido_periodo ON public.inventario_pedido(periodo, estado);
CREATE INDEX IF NOT EXISTS idx_inventario_recepcion_pedido ON public.inventario_pedido_recepcion(pedido_id, creado_en);
CREATE INDEX IF NOT EXISTS idx_inventario_recepcion_detalle_producto ON public.inventario_pedido_recepcion_detalle(producto_id);

-- El último conteo finalizado constituye la base; solo se suman
-- recepciones posteriores a ese conteo (sin duplicar ingresos antiguos).
-- Se incluyen productos habilitados aunque aún no haya conteos.
CREATE OR REPLACE VIEW public.v_inventario_stock_actual AS
WITH ultimo_conteo AS (
  SELECT DISTINCT ON (i.plaza_id, d.producto_id)
    i.plaza_id, d.producto_id, i.id inventario_id,
    i.fecha_finalizacion, d.cantidad_encontrada
  FROM public.inventario_conteo i
  JOIN public.inventario_conteo_detalle d ON d.inventario_id = i.id
  WHERE i.estado::text = 'FINALIZADO'
  ORDER BY i.plaza_id, d.producto_id, i.fecha_finalizacion DESC, i.id DESC
)
SELECT
  pp.plaza_id,
  pl.codigo AS plaza,
  pp.producto_id,
  pr.nombre::varchar(200) AS producto,
  pr.unidad_medida::varchar(80) AS unidad_medida,
  (COALESCE(uc.cantidad_encontrada, 0) + COALESCE(entradas.cantidad, 0))::numeric(12,2) AS cantidad_actual,
  COALESCE(uc.inventario_id, 0)::bigint AS inventario_id,
  GREATEST(uc.fecha_finalizacion, entradas.ultima_fecha) AS actualizado_en
FROM public.inventario_producto_plaza pp
JOIN public.inventario_producto pr ON pr.id = pp.producto_id
JOIN public.plazas pl ON pl.id = pp.plaza_id
LEFT JOIN ultimo_conteo uc ON uc.plaza_id = pp.plaza_id AND uc.producto_id = pp.producto_id
LEFT JOIN LATERAL (
  SELECT SUM(rd.cantidad) cantidad, MAX(r.creado_en) ultima_fecha
  FROM public.inventario_pedido_recepcion_detalle rd
  JOIN public.inventario_pedido_recepcion r ON r.id = rd.recepcion_id
  JOIN public.inventario_pedido ped ON ped.id = r.pedido_id
  WHERE ped.plaza_id = pp.plaza_id
    AND rd.producto_id = pp.producto_id
    AND (uc.fecha_finalizacion IS NULL OR r.creado_en > uc.fecha_finalizacion)
) entradas ON TRUE;

-- Consumido entre conteos = stock anterior + entradas intermedias - stock observado.
-- Sin dos conteos consecutivos no hay consumo verificable, por lo que
-- ninguna recomendación histórica puede tratar una estimación como dato real.
CREATE OR REPLACE VIEW public.v_inventario_consumo_mensual AS
WITH lecturas AS (
  SELECT i.plaza_id, d.producto_id,
         i.fecha_finalizacion fecha,
         d.cantidad_encontrada actual,
         LAG(i.fecha_finalizacion) OVER w anterior_fecha,
         LAG(d.cantidad_encontrada) OVER w anterior
  FROM public.inventario_conteo i
  JOIN public.inventario_conteo_detalle d ON d.inventario_id=i.id
  WHERE i.estado::text='FINALIZADO'
  WINDOW w AS (PARTITION BY i.plaza_id,d.producto_id ORDER BY i.fecha_finalizacion,i.id)
), consumos AS (
  SELECT l.plaza_id, l.producto_id,
         DATE_TRUNC('month', l.fecha)::date periodo,
         GREATEST(0, l.anterior + COALESCE((
           SELECT SUM(rd.cantidad)
           FROM public.inventario_pedido_recepcion_detalle rd
           JOIN public.inventario_pedido_recepcion r ON r.id=rd.recepcion_id
           JOIN public.inventario_pedido pe ON pe.id=r.pedido_id
           WHERE pe.plaza_id=l.plaza_id AND rd.producto_id=l.producto_id
             AND r.creado_en > l.anterior_fecha AND r.creado_en <= l.fecha
         ),0) - l.actual) consumo
  FROM lecturas l WHERE l.anterior_fecha IS NOT NULL
)
SELECT plaza_id,producto_id,periodo,SUM(consumo)::numeric(14,2) consumo
FROM consumos GROUP BY plaza_id,producto_id,periodo;

